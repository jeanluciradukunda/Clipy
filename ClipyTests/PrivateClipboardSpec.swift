import Quick
import Nimble
@testable import Clipy

class PrivateClipboardSpec: QuickSpec {
    override class func spec() {

        describe("ClipService.isMarkedPrivate") {
            for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
                it("skips content marked \(marker)") {
                    expect(ClipService.isMarkedPrivate([.string, NSPasteboard.PasteboardType(marker)])) == true
                }
            }

            it("keeps ordinary content") {
                expect(ClipService.isMarkedPrivate([.string, .rtf, .png])) == false
            }

            it("reads the markers from a real pasteboard") {
                let pasteboard = NSPasteboard(name: NSPasteboard.Name("com.clipy-app.Clipy.tests.\(UUID().uuidString)"))
                defer { pasteboard.releaseGlobally() }
                pasteboard.declareTypes([.string, NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")], owner: nil)
                pasteboard.setString("hunter2", forType: .string)
                expect(ClipService.isMarkedPrivate(pasteboard.types ?? [])) == true
            }
        }
    }
}
